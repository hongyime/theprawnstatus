create table public.status_collector_leases (
  runner text primary key,
  enabled boolean not null default false,
  capacity_limit_bytes bigint not null default 400000000 check (capacity_limit_bytes between 1000000 and 400000000),
  targets jsonb not null check (jsonb_typeof(targets) = 'array' and jsonb_array_length(targets) between 1 and 24 and octet_length(targets::text) <= 100000),
  lease_token uuid,
  lease_slot timestamptz,
  lease_targets jsonb,
  leased_at timestamptz,
  lease_expires_at timestamptz,
  committed_slot timestamptz
);

create table public.status_target_configs (
  hash bytea primary key,
  targets jsonb not null,
  check (hash = sha256(convert_to(targets::text, 'UTF8'))),
  check (jsonb_typeof(targets) = 'array' and jsonb_array_length(targets) between 1 and 24 and octet_length(targets::text) <= 100000)
);

create table public.status_probe_batches (
  runner text not null,
  slot timestamptz not null,
  token uuid not null unique,
  first_checked_at timestamptz not null,
  last_checked_at timestamptz not null,
  target_config_hash bytea not null references public.status_target_configs(hash),
  records jsonb not null check (jsonb_typeof(records) = 'array' and jsonb_array_length(records) between 1 and 24),
  created_at timestamptz not null default now(),
  primary key (runner, slot),
  check (last_checked_at >= first_checked_at and last_checked_at - first_checked_at <= interval '120 seconds')
);
create index status_probe_batches_window_idx on public.status_probe_batches (runner, first_checked_at);

