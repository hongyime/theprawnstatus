-- Existing manual imports and an in-flight legacy job remain compatible during
-- cutover. New collection never appends a redundant historical snapshot.
create function public.insert_legacy_status_run()
returns trigger language plpgsql security invoker set search_path = '' as $$
begin
  if new.id is not null then raise exception 'Status run ID is generated by the database'; end if;
  insert into public.status_runs_legacy (runner, generated_at, window_days, target_count, summary, created_at)
    values (new.runner, new.generated_at, new.window_days, new.target_count, new.summary, new.created_at)
    returning id, runner, generated_at, window_days, target_count, summary, created_at into new;
  return new;
end;
$$;
revoke all on function public.insert_legacy_status_run() from public, anon, authenticated;
grant execute on function public.insert_legacy_status_run() to service_role;
create trigger status_runs_legacy_insert instead of insert on public.status_runs
  for each row execute function public.insert_legacy_status_run();

